#!/usr/bin/env node
/* Availability canonicality — does the seller's timetable actually reach buyers?
 *
 *   firebase emulators:exec --only firestore --project sokoni-avail-test \
 *     "node scripts/test-availability-canonical.js"
 *
 * WHY
 * availability-manager.html wrote the timetable as `schedule.monday{…}` plus an
 * `/overrides/{date}` subcollection. computeEffectiveAvailability() reads `hours[mon]`
 * and an `overrides[ymd]` document map. Field name, day-key format and storage kind all
 * differed, so a shop marked closed still resolved to reason:'no_schedule' → open:true.
 * Opening hours and closed dates produced NO buyer-visible effect whatsoever.
 *
 * These tests drive the REAL resolver from functions/kasshop.js against seeded Firestore
 * documents. They cannot pass on DOM markup, localStorage or a mock: every assertion is
 * the value the storefront would be handed.
 *
 * The adapter under test is sokoni-availability-schedule.js — the same module the page
 * uses, so a shape regression fails here rather than silently in production.
 */
'use strict';
process.env.FIRESTORE_EMULATOR_HOST = process.env.FIRESTORE_EMULATOR_HOST || '127.0.0.1:8080';
process.env.GCLOUD_PROJECT = process.env.GCLOUD_PROJECT || 'sokoni-avail-test';

const path = require('path');
const FUNCTIONS_DIR = path.resolve(__dirname, '..', 'functions');
/* firebase-admin is installed under functions/, not the repo root — resolve it the
   same way scripts/test-kasshop-boundary.js does. */
const admin = require(require.resolve('firebase-admin', { paths: [FUNCTIONS_DIR] }));
const SAS = require('../sokoni-availability-schedule.js');

admin.initializeApp({ projectId: process.env.GCLOUD_PROJECT });
const db = admin.firestore();

let pass = 0, fail = 0;
const ck = (l, ok, d) => {
  console.log('  ' + (ok ? 'PASS  ' : 'FAIL  ') + l + (d !== undefined ? '   [' + String(d).slice(0, 100) + ']' : ''));
  ok ? pass++ : fail++;
};

const A = 'seller-A-uid', B = 'seller-B-uid';
const SHOP_A = 'shopA', SHOP_B = 'shopB';

/* EAT is UTC+3 and computeEffectiveAvailability is called with tzOffsetMin=180.
   Pick instants whose Nairobi-local weekday/time are unambiguous. */
const MON_10AM = Date.parse('2026-08-10T07:00:00Z');   /* Mon 10:00 EAT */
const MON_1230 = Date.parse('2026-08-10T09:30:00Z');   /* Mon 12:30 EAT — inside the split gap */
const MON_3PM  = Date.parse('2026-08-10T12:00:00Z');   /* Mon 15:00 EAT */
const SUN_10AM = Date.parse('2026-08-09T07:00:00Z');   /* Sun 10:00 EAT */
const TUE_10AM = Date.parse('2026-08-11T07:00:00Z');   /* Tue 10:00 EAT — a different DATE */

async function seedShop(shopId, sellerUid, live) {
  await db.collection('shops').doc(shopId).set(Object.assign({ sellerUid }, live || {}));
}
async function seedSchedule(uid, legacySchedule, overrideDocs) {
  /* Write EXACTLY what availability-manager.html writes: legacy shape + canonical
     projection generated by the shared adapter. If the adapter is wrong, so is this. */
  await db.collection('providerAvailability').doc(uid).set({
    uid,
    schedule: legacySchedule,
    hours: SAS.toCanonicalHours(legacySchedule),
    overrides: SAS.toCanonicalOverrides(overrideDocs || []),
  });
  for (const o of (overrideDocs || [])) {
    await db.collection('providerAvailability').doc(uid).collection('overrides').doc(o.date).set(o);
  }
}

const OPEN_9_5 = { closed: false, periods: [{ open: '09:00', close: '17:00' }], breaks: [] };
const SPLIT = { closed: false, periods: [{ open: '08:00', close: '12:00' }, { open: '13:00', close: '17:00' }], breaks: [] };
const CLOSED = { closed: true, periods: [], breaks: [] };
const WEEK = (mon) => ({
  monday: mon, tuesday: OPEN_9_5, wednesday: OPEN_9_5, thursday: OPEN_9_5,
  friday: OPEN_9_5, saturday: CLOSED, sunday: CLOSED,
});

(async () => {
  const kasshop = require('../functions/kasshop.js');
  const effectiveForShop = kasshop.effectiveForShop;
  const publicShopState = kasshop.publicShopState;

  /* ── A. live state overrides everything ── */
  console.log('\nA. ONLINE/OFFLINE reaches the buyer decision');
  await seedShop(SHOP_A, A, { online: true, acceptingOrders: true, delivery: true, pickup: true });
  await seedSchedule(A, WEEK(OPEN_9_5), []);
  let eff = await effectiveForShop(SHOP_A, MON_10AM);
  ck('online + inside hours → open', eff && eff.open === true, eff && eff.reason);

  await db.collection('shops').doc(SHOP_A).set({ online: false }, { merge: true });
  eff = await effectiveForShop(SHOP_A, MON_10AM);
  ck('seller OFFLINE → closed regardless of schedule', eff && eff.open === false, eff && eff.reason);
  ck('  …and the reason is the live switch, not the timetable',
     eff && eff.source === 'live', eff && eff.source);

  await db.collection('shops').doc(SHOP_A).set({ online: true }, { merge: true });
  await db.collection('shops').doc(SHOP_A).set({ acceptingOrders: false }, { merge: true });
  eff = await effectiveForShop(SHOP_A, MON_10AM);
  ck('acceptingOrders=false → closed', eff && eff.open === false, eff && eff.reason);
  await db.collection('shops').doc(SHOP_A).set({ acceptingOrders: true }, { merge: true });

  /* ── B. split periods ── */
  console.log('\nB. Split shift 08:00–12:00 and 13:00–17:00');
  await seedSchedule(A, WEEK(SPLIT), []);
  ck('10:00 → open (first period)', (await effectiveForShop(SHOP_A, MON_10AM)).open === true);
  ck('12:30 → CLOSED (the gap between periods)',
     (await effectiveForShop(SHOP_A, MON_1230)).open === false);
  ck('15:00 → open (second period)', (await effectiveForShop(SHOP_A, MON_3PM)).open === true);
  const proj = SAS.toCanonicalHours(WEEK(SPLIT));
  ck('both periods survive the shape adapter', proj.mon.periods.length === 2,
     JSON.stringify(proj.mon.periods));

  /* ── C. date override beats the weekly schedule ── */
  console.log('\nC. Closing one specific date');
  await seedSchedule(A, WEEK(OPEN_9_5), [{ date: '2026-08-10', closed: true, label: 'Stock take' }]);
  eff = await effectiveForShop(SHOP_A, MON_10AM);
  ck('override closes a normally-open day', eff.open === false, eff.reason);
  ck('  …and reports itself as an override', eff.source === 'override', eff.source);
  /* Must be a genuinely different DATE. Asserting against MON_3PM would pass because the
     override closed that same date — a true result for the wrong reason. */
  const tue = await effectiveForShop(SHOP_A, TUE_10AM);
  ck('the NEXT day is unaffected by the override', tue.open === true, tue.reason);
  ck('  …and resolves from the schedule, not the override', tue.source === 'schedule', tue.source);

  /* ── D. removing the override restores the weekly schedule ── */
  console.log('\nD. Removing the override');
  await seedSchedule(A, WEEK(OPEN_9_5), []);
  eff = await effectiveForShop(SHOP_A, MON_10AM);
  ck('weekly schedule effective again', eff.open === true, eff.reason);

  /* Special-hours override: open on a normally CLOSED day. */
  await seedSchedule(A, WEEK(OPEN_9_5), [{ date: '2026-08-09', closed: false, periods: [{ open: '08:00', close: '18:00' }] }]);
  eff = await effectiveForShop(SHOP_A, SUN_10AM);
  ck('special-hours override opens a closed Sunday', eff.open === true, eff.reason);

  /* ── E. the projection is per-seller ── */
  console.log('\nE. Seller isolation of the schedule');
  await seedShop(SHOP_B, B, { online: true, acceptingOrders: true });
  await seedSchedule(B, WEEK(CLOSED), []);
  const effA = await effectiveForShop(SHOP_A, MON_10AM);
  const effB = await effectiveForShop(SHOP_B, MON_10AM);
  ck("A's shop resolves from A's schedule", effA.open === true, effA.reason);
  ck("B's shop resolves from B's schedule (closed)", effB.open === false, effB.reason);
  ck('the two do not share state', effA.open !== effB.open);

  /* ── F. publicShopState carries schedule + effective decision together ── */
  console.log('\nF. publicShopState — the storefront contract');
  const st = await publicShopState(SHOP_A, A);
  ck('returns an availability decision', !!(st && st.availability), JSON.stringify(st && st.availability));
  ck('returns the schedule the seller manages', !!(st && st.schedule && st.schedule.hours),
     JSON.stringify(st && st.schedule && Object.keys(st.schedule.hours || {})));
  ck('schedule uses canonical short day keys',
     !!(st.schedule.hours && st.schedule.hours.mon), Object.keys(st.schedule.hours || {}).join(','));
  ck('delivery/pickup surfaced to the buyer',
     st.availability.delivery !== undefined && st.availability.pickup !== undefined,
     'delivery=' + st.availability.delivery + ' pickup=' + st.availability.pickup);

  /* ── G. unknown must not read as open ── */
  console.log('\nG. Unresolvable shop');
  const missing = await publicShopState('no-such-shop', A);
  ck('missing shop → availability null, NOT open',
     missing && missing.availability === null, JSON.stringify(missing));

  /* ── H. legacy seller: schedule only, no projection ── */
  console.log('\nH. Legacy seller with the OLD shape only');
  await db.collection('providerAvailability').doc(A).set({ uid: A, schedule: WEEK(CLOSED) });
  eff = await effectiveForShop(SHOP_A, MON_10AM);
  ck('legacy-only schedule does NOT reach the resolver (documents the bug)',
     eff.reason === 'no_schedule', eff.reason);
  /* Now apply exactly what the page's repair does, and re-check. */
  const legacy = (await db.collection('providerAvailability').doc(A).get()).data();
  const repaired = SAS.project(legacy, []);
  ck('adapter flags the legacy doc as needing repair', repaired.needsRepair === true);
  await db.collection('providerAvailability').doc(A).set(
    { hours: repaired.hours, overrides: repaired.overrides }, { merge: true });
  eff = await effectiveForShop(SHOP_A, MON_10AM);
  ck('after repair the closed Monday IS effective', eff.open === false, eff.reason);
  const after = (await db.collection('providerAvailability').doc(A).get()).data();
  ck('repair preserved the legacy schedule (no data loss)',
     !!(after.schedule && after.schedule.monday), Object.keys(after.schedule || {}).join(','));

  console.log('\n' + (fail ? '✗ ' : '✓ ') + pass + ' passed, ' + fail + ' failed\n');
  process.exit(fail ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
