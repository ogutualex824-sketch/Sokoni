#!/usr/bin/env node
/* Generates sokoni-legal-taxonomy.js (browser) from THE source, functions/shared/legal-taxonomy.js.
 *   node scripts/build-legal-taxonomy.js           write
 *   node scripts/build-legal-taxonomy.js --check   exit 1 when the committed copy is stale (no write)
 * The browser file is an ARTIFACT: never hand-edit it; change the source and regenerate. */
'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'sokoni-legal-taxonomy.js');

function render(T) {
  const data = { groups: T.GROUPS.map((g) => ({ id: g.id, label: g.label, icon: g.icon, services: g.services.map((s) => ({ id: s.id, label: s.label })) })),
    legacy: T.LEGACY_TO_AREA, maxAreas: T.MAX_AREAS,
    specialist: (T.SPECIALIST || []).map((x) => ({ id: x.id, label: x.label, icon: x.icon, eligibility: x.eligibility, note: x.note })) };
  const json = JSON.stringify(data, null, 2);
  const hash = crypto.createHash('sha256').update(json).digest('hex').slice(0, 16);
  return `/* GENERATED by scripts/build-legal-taxonomy.js from functions/shared/legal-taxonomy.js — DO NOT EDIT.
 * source-hash: ${hash}
 * The ONE Legal Hub taxonomy, browser copy. The server validates every stored value against the source. */
(function (root) {
  'use strict';
  var DATA = ${json};
  var AREA = {};
  DATA.groups.forEach(function (g) { g.services.forEach(function (s) { AREA[s.id] = { id: s.id, label: s.label, group: g.id }; }); });
  function areasOfProfile(p) {
    var own = (p && Array.isArray(p.practiceAreas) ? p.practiceAreas : []).filter(function (a) { return !!AREA[a]; });
    if (own.length) return own;
    var out = [];
    (p && Array.isArray(p.specializations) ? p.specializations : []).forEach(function (s) { var a = DATA.legacy[s]; if (a && out.indexOf(a) < 0) out.push(a); });
    return out;
  }
  root.SokoniLegalTaxonomy = Object.freeze({
    HASH: '${hash}', GROUPS: DATA.groups, AREA: AREA, MAX_AREAS: DATA.maxAreas,
    SPECIALIST: DATA.specialist || [],
    label: function (id) { if (AREA[id]) return AREA[id].label; var sp = (DATA.specialist || []).filter(function (x) { return x.id === id; })[0]; return sp ? sp.label : ''; },
    isSpecialist: function (id) { return (DATA.specialist || []).some(function (x) { return x.id === id; }); },
    groupOf: function (id) { return AREA[id] ? AREA[id].group : null; },
    groupLabel: function (gid) { var g = DATA.groups.filter(function (x) { return x.id === gid; })[0]; return g ? g.label : ''; },
    areasOfProfile: areasOfProfile,
  });
})(typeof window !== 'undefined' ? window : this);
`;
}

const T = require(path.join(ROOT, 'functions', 'shared', 'legal-taxonomy.js'));
const want = render(T);
if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : null;
  if (have !== want) { console.error('STALE: sokoni-legal-taxonomy.js does not match functions/shared/legal-taxonomy.js — run node scripts/build-legal-taxonomy.js'); process.exit(1); }
  console.log('sokoni-legal-taxonomy.js is current');
} else { fs.writeFileSync(OUT, want); console.log('wrote sokoni-legal-taxonomy.js'); }
module.exports = { render };
