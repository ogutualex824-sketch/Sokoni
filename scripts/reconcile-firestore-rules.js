/* READ-ONLY. Categorise every local firestore.rules line that is NOT in the live ruleset.
   Writes a markdown reconciliation artifact. Changes no rules and touches no production. */
'use strict';
const fs = require('fs');

const live = fs.readFileSync('firestore.rules.live', 'utf8').split(/\r?\n/);
const local = fs.readFileSync('firestore.rules', 'utf8').split(/\r?\n/);

/* Multiset of live lines (trimmed) so we can spot local-only lines regardless of position. */
const liveCount = new Map();
live.forEach((l) => { const k = l.trim(); liveCount.set(k, (liveCount.get(k) || 0) + 1); });
const remaining = new Map(liveCount);

/* Walk local, tracking the enclosing top-level match block. */
const CAT = [
  [/deliveries|packageRequests|driverLoc|driverLat|driverLng/i, 'delivery tracking'],
  [/analytic/i, 'analytics'],
  [/etims|creditNote|debitNote|invoiceCancel|invoiceAmend|invoiceRevers/i, 'eTIMS / fiscal documents'],
  [/branch|merchantId/i, 'branches'],
];
const categorise = (block, line) => {
  const hay = block + ' ' + line;
  for (const [re, name] of CAT) if (re.test(hay)) return name;
  return 'other';
};

let block = '(file root)';
const unreleased = [];
local.forEach((raw, i) => {
  const t = raw.trim();
  const m = raw.match(/^\s{4}match\s+(\S+)/);
  if (m) block = m[1];
  if (!t) return;
  const n = remaining.get(t) || 0;
  if (n > 0) { remaining.set(t, n - 1); return; }   /* matched a live line */
  unreleased.push({ line: i + 1, block, text: raw, cat: categorise(block, t) });
});

/* Live lines never matched by local = REMOVED locally (should be none, and matters most). */
const removed = [];
remaining.forEach((n, k) => { for (let i = 0; i < n; i++) if (k) removed.push(k); });

const byCat = new Map();
unreleased.forEach((u) => { if (!byCat.has(u.cat)) byCat.set(u.cat, []); byCat.get(u.cat).push(u); });

const esc = (s) => s.replace(/\|/g, '\\|');
let md = '';
md += '# Firestore rules reconciliation — 2026-08-11\n\n';
md += '> Generated by `scripts/` reconciliation run. **Read-only**: no rules were changed.\n\n';
md += '## Baselines\n\n';
md += '| artifact | meaning | bytes |\n|---|---|---|\n';
md += `| \`firestore.rules.live\` | **exact source of the LIVE ruleset** \`ca9e8924-98b7-4201-b5ba-d529970ecd38\` — the safe, recoverable baseline | ${Buffer.byteLength(live.join('\n'), 'utf8').toLocaleString()} |\n`;
md += `| \`firestore.rules\` | local working source | ${Buffer.byteLength(local.join('\n'), 'utf8').toLocaleString()} |\n\n`;
md += `**Live release:** \`cloud.firestore\` → \`projects/sokoni-aeb26/rulesets/ca9e8924-98b7-4201-b5ba-d529970ecd38\`\n\n`;

md += '## Summary\n\n';
md += `Local contains **${unreleased.length} lines that are NOT in the live ruleset**, across ${byCat.size} categories.\n`;
md += `Live contains **${removed.length} lines not present locally**.\n\n`;
md += '| category | unreleased lines |\n|---|---|\n';
[...byCat.entries()].sort((a, b) => b[1].length - a[1].length)
  .forEach(([c, arr]) => { md += `| ${c} | ${arr.length} |\n`; });
md += '\n';

md += '## Why this matters\n\n';
md += 'The live ruleset is the previous baseline **plus only the 5 delivery-position lines**.\n';
md += 'Every other local change below has **never been released**. A `firebase deploy --only firestore:rules`\n';
md += 'would attempt to promote all of them at once — which is what produced the\n';
md += '`PATCH /releases/cloud.firestore → 400 INVALID_ARGUMENT` followed by the CLI\'s misleading\n';
md += '`POST /releases → 409 ALREADY_EXISTS`. A minimal candidate (live + 5 lines) promoted cleanly,\n';
md += 'which is how the delivery change reached production.\n\n';
md += '**Nothing here is deleted.** The complete pre-reconciliation working file is preserved verbatim\n';
md += 'as `firestore.rules.unreleased`, and in git history.\n\n';

md += '## Unreleased changes by category\n\n';
[...byCat.entries()].sort((a, b) => b[1].length - a[1].length).forEach(([cat, arr]) => {
  md += `### ${cat} — ${arr.length} lines\n\n`;
  const blocks = [...new Set(arr.map((a) => a.block))];
  md += `Blocks touched: ${blocks.map((b) => '`' + b + '`').join(', ')}\n\n`;
  md += '| local line | block | rule text |\n|---|---|---|\n';
  arr.slice(0, 60).forEach((a) => {
    md += `| ${a.line} | \`${esc(a.block)}\` | \`${esc(a.text.trim().slice(0, 110))}\` |\n`;
  });
  if (arr.length > 60) md += `\n_…and ${arr.length - 60} more._\n`;
  md += '\n';
});

if (removed.length) {
  md += '## Present in LIVE but missing locally (investigate before any deploy)\n\n';
  removed.slice(0, 40).forEach((l) => { md += `- \`${esc(l.slice(0, 120))}\`\n`; });
  if (removed.length > 40) md += `\n_…and ${removed.length - 40} more._\n`;
  md += '\n';
}

md += '## How to release any of these deliberately\n\n';
md += '1. Start from `firestore.rules.live` (the known-good baseline).\n';
md += '2. Apply **one category** of changes, scoped to its own `match` block.\n';
md += '3. Run the emulator suites against the candidate:\n';
md += '   `RULES_FILE=<candidate> firebase emulators:exec --only firestore --project <test> "node scripts/test-*-rules.js"`\n';
md += '4. Diff the candidate against `firestore.rules.live` and confirm **only** the intended lines changed.\n';
md += '   A naive string replace previously landed a driver-position grant in `match /orders/{orderId}`\n';
md += '   instead of `match /deliveries/{deliveryId}` — anchor edits inside the target block.\n';
md += '5. Create the ruleset, then promote the release, then re-read the live ruleset to verify.\n\n';
md += '**Owner action required:** the analytics, eTIMS, branches and credit/debit rules below are believed\n';
md += 'by their authors to be deployed. They are not. Each owner should validate and release their own set.\n';

fs.writeFileSync('docs/RULES_RECONCILIATION.md', md);
console.log('unreleased lines :', unreleased.length);
console.log('missing locally  :', removed.length);
[...byCat.entries()].sort((a, b) => b[1].length - a[1].length)
  .forEach(([c, arr]) => console.log('   ', c.padEnd(26), arr.length));
console.log('\nwrote docs/RULES_RECONCILIATION.md');
