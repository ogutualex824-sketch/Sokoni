#!/usr/bin/env node
/* Generates sokoni-marketing-taxonomy.js (browser) from THE source, functions/shared/marketing-taxonomy.js.
 *   node scripts/build-marketing-taxonomy.js           write
 *   node scripts/build-marketing-taxonomy.js --check   exit 1 when the committed copy is stale (no write) */
'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'sokoni-marketing-taxonomy.js');
function render(T) {
  const data = { groups: T.GROUPS.map((g) => ({ id: g.id, label: g.label, icon: g.icon, services: g.services.map((s) => ({ id: s.id, label: s.label, model: s.model })) })),
    types: T.APPLICATION_TYPES, legacy: T.LEGACY_TO_AREA };
  const json = JSON.stringify(data, null, 2);
  const hash = crypto.createHash('sha256').update(json).digest('hex').slice(0, 16);
  return `/* GENERATED by scripts/build-marketing-taxonomy.js from functions/shared/marketing-taxonomy.js — DO NOT EDIT.
 * source-hash: ${hash}
 * The ONE Marketing Hub taxonomy, browser copy. The server validates every stored value against the source. */
(function (root) {
  'use strict';
  var DATA = ${json};
  var AREA = {};
  DATA.groups.forEach(function (g) { g.services.forEach(function (s) { AREA[s.id] = { id: s.id, label: s.label, group: g.id, model: s.model }; }); });
  root.SokoniMarketingTaxonomy = Object.freeze({
    HASH: '${hash}', GROUPS: DATA.groups, AREA: AREA, TYPES: DATA.types,
    label: function (id) { return AREA[id] ? AREA[id].label : ''; },
    groupOf: function (id) { return AREA[id] ? AREA[id].group : null; },
    modelOf: function (id) { return AREA[id] ? AREA[id].model : null; },
  });
})(typeof window !== 'undefined' ? window : this);
`;
}
const T = require(path.join(ROOT, 'functions', 'shared', 'marketing-taxonomy.js'));
const want = render(T);
if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : null;
  if (have !== want) { console.error('STALE: sokoni-marketing-taxonomy.js — run node scripts/build-marketing-taxonomy.js'); process.exit(1); }
  console.log('sokoni-marketing-taxonomy.js is current');
} else { fs.writeFileSync(OUT, want); console.log('wrote sokoni-marketing-taxonomy.js'); }
