/* ══════════════════════════════════════════════════════════════════════════
   SOKONI — App release metrics: the admin release log + install/update counts
   functions/app-release-metrics.js

   FOUR ENTRY POINTS (re-exported BY NAME in functions/index.js)
     adminReleaseLog          onCall, admin      — a page of the release log
     appInstallReport         onCall, public     — one device says "installed" / "still here, on build X"
     scheduledAppInstallStats onSchedule, 6 h    — count() aggregate → appInstallMetrics/summary
     adminGetAppInstallStats  onCall, admin      — that aggregate, or { state: 'not-computed-yet' }

   OWNER DECISIONS THIS IMPLEMENTS (2026-10-01; docs/ADMIN_UPDATES_CENTER_CENSUS.md)
   A  The release log is ADMIN-ONLY. It is bundled INSIDE the functions source
      (functions/data/release-log.json, generated by scripts/build-release-log.js)
      and returned only to a caller holding the admin claim. Hosting never serves
      it: 33 of 775 entries describe security defects.
   B  Install / update figures come ONLY from the aggregate this module writes.
      No figure is back-filled or estimated for the period before it shipped.
      An absent aggregate is returned as { state: 'not-computed-yet' } — never 0.
   C  NO RULES CHANGE. Every write here is the Admin SDK; every read by a person
      goes through an admin-checked callable. Both collections this module owns —
      `appInstalls` and `appInstallMetrics` — have NO match block in
      firestore.rules, so Firestore's default-deny refuses all client access.
      (`platformMetrics` was NOT used for the aggregate: firestore.rules gives it
      `read: isModerator()` and `write: isAdmin()`, so an admin browser could
      overwrite the canonical figure. A server-only figure needs a rule-less path.)

   NO COMPOSITE INDEX. Every query is a single-field equality, a single-field
   range, or a single-field orderBy — all served by Firestore's automatic
   single-field indexes. firestore.indexes.json is untouched.

   PRIVACY. appInstalls stores no uid, no IP, no user-agent string. The IP is read
   only to form a hashed rate-limit key and is never written to Firestore.
   ══════════════════════════════════════════════════════════════════════════ */
'use strict';

const crypto = require('crypto');
const { onCall, HttpsError } = require('firebase-functions/v2/https');
const { onSchedule } = require('firebase-functions/v2/scheduler');
const logger = require('firebase-functions/logger');
const { assertAdmin } = require('./shared/errors');

const REGION = 'us-central1';
const INSTALLS = 'appInstalls';
const METRICS_COLL = 'appInstallMetrics';
const METRICS_DOC = 'summary';
const LIVE_VERSION_URL = 'https://mysokoni.co.ke/version.json';
const LIVE_FETCH_TIMEOUT_MS = 5000;
const DAY_MS = 86400000;
const EAT_OFFSET_MS = 3 * 3600000;   /* Africa/Nairobi is UTC+3, no DST */

const UUID_V4 = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;
const CACHE_VERSION = /^sokoni-\d{14}-v\d+$/;
const EVENTS = new Set(['install', 'checkin']);
const PLATFORMS = new Set(['android', 'ios', 'windows', 'macos', 'linux', 'chromeos', 'other']);

const LOG_TYPES = new Set(['all', 'fix', 'feat', 'deploy', 'docs', 'test', 'other']);
const LOG_STATUSES = new Set(['all', 'live', 'deployed', 'not-deployed', 'committed']);
const LOG_LIMIT_MAX = 100;
const LOG_LIMIT_DEFAULT = 40;
const LOG_QUERY_MAX = 100;

/* ── dependency seam (tests replace these; production uses the real ones) ── */
const _deps = {
  db: () => require('firebase-admin/firestore').getFirestore(),
  serverTimestamp: () => require('firebase-admin/firestore').FieldValue.serverTimestamp(),
  timestampFromMillis: (ms) => require('firebase-admin/firestore').Timestamp.fromMillis(ms),
  now: () => Date.now(),
  /* Rate limit through the EXISTING limiter (redis-rate-limiter.js). queryRateLimit
     keys on an identifier we choose, so the key is installId + a hash of the IP.
     'default' is not a security action there, so when Redis is unavailable it
     passes (fails open) — the day key below is the hard write bound either way. */
  rateLimit: (identifier) => require('./redis-rate-limiter')
    .queryRateLimit(identifier, 'default', { maxRequests: 12, windowSeconds: 3600 }),
  fetch: (...a) => fetch(...a),
  /* Loaded lazily, on the first admin call — never at cold start of the other
     ~1,700 functions that share this index.js. Static path: the require-closure
     gate resolves it against the committed tree. */
  releaseLog: () => require('./data/release-log.json'),
};

/* ═══════════════════════════ pure helpers ═══════════════════════════════ */

/** Nairobi calendar day, 'YYYY-MM-DD'. The idempotency day key. */
function dayKey(ms) {
  return new Date(ms + EAT_OFFSET_MS).toISOString().slice(0, 10);
}

/** Validate a report payload. Returns the normalised input or throws invalid-argument. */
function validateReport(d) {
  if (!d || typeof d !== 'object' || Array.isArray(d)) throw new HttpsError('invalid-argument', 'Payload required.');
  const installId = typeof d.installId === 'string' ? d.installId.toLowerCase() : '';
  if (!UUID_V4.test(installId)) throw new HttpsError('invalid-argument', 'installId must be a UUID v4.');
  if (!EVENTS.has(d.event)) throw new HttpsError('invalid-argument', 'event must be install or checkin.');
  if (typeof d.cacheVersion !== 'string' || d.cacheVersion.length > 64 || !CACHE_VERSION.test(d.cacheVersion)) {
    throw new HttpsError('invalid-argument', 'cacheVersion is not a SOKONI build id.');
  }
  if (typeof d.standalone !== 'boolean') throw new HttpsError('invalid-argument', 'standalone must be a boolean.');
  if (!PLATFORMS.has(d.platform)) throw new HttpsError('invalid-argument', 'platform is not recognised.');
  return { installId, event: d.event, cacheVersion: d.cacheVersion, standalone: d.standalone, platform: d.platform };
}

function _clientIp(req) {
  const raw = (req && req.rawRequest) || {};
  const h = raw.headers || {};
  const xff = typeof h['x-forwarded-for'] === 'string' ? h['x-forwarded-for'].split(',')[0].trim() : '';
  return xff || h['x-real-ip'] || raw.ip || 'unknown';
}

/** A one-way, truncated hash of the caller IP. Used ONLY inside a rate-limit key; never stored. */
function ipHash(req) {
  return crypto.createHash('sha256').update('sokoni-install-rl:' + _clientIp(req)).digest('hex').slice(0, 16);
}

/* ══════════════════════ appInstallReport (public) ═══════════════════════ */

/**
 * Record one report. At most ONE write per installId per Nairobi day for check-ins;
 * the install flag is set at most once, ever. First sight is create() — never set() —
 * so a concurrent first report cannot overwrite another (the transaction retries and
 * then sees the document).
 * @returns {Promise<{ok:true, action:'created'|'updated'|'deduped'}>}
 */
async function recordReport(db, input, nowMs) {
  const day = dayKey(nowMs);
  const ref = db.collection(INSTALLS).doc(input.installId);
  return db.runTransaction(async (tx) => {
    const ts = _deps.serverTimestamp();
    const snap = await tx.get(ref);
    if (!snap.exists) {
      const doc = {
        schema: 1,
        firstSeenAt: ts,
        lastSeenAt: ts,
        lastSeenDay: day,
        firstCacheVersion: input.cacheVersion,
        cacheVersion: input.cacheVersion,
        standalone: input.standalone,
        platform: input.platform,
        installed: input.event === 'install',
      };
      if (input.event === 'install') doc.installedAt = ts;
      tx.create(ref, doc);
      return { ok: true, action: 'created' };
    }
    const cur = snap.data() || {};
    const newDay = cur.lastSeenDay !== day;
    const newInstall = input.event === 'install' && cur.installed !== true;
    if (!newDay && !newInstall) return { ok: true, action: 'deduped' };
    const upd = {};
    if (newDay) {
      upd.lastSeenAt = ts;
      upd.lastSeenDay = day;
      upd.cacheVersion = input.cacheVersion;
      upd.standalone = input.standalone;
    }
    if (newInstall) { upd.installed = true; upd.installedAt = ts; }
    tx.update(ref, upd);
    return { ok: true, action: 'updated' };
  });
}

async function handleAppInstallReport(req) {
  const input = validateReport(req && req.data);
  try {
    const rl = await _deps.rateLimit('appInstall:' + input.installId + ':' + ipHash(req));
    if (rl && rl.allowed === false) return { ok: false, throttled: true };
  } catch (e) {
    /* A limiter fault must not drop a report; the day key still bounds writes. */
  }
  try {
    return await recordReport(_deps.db(), input, _deps.now());
  } catch (e) {
    /* Telemetry never surfaces an internal failure to a public caller. */
    logger.error('[appInstallReport] write failed', { err: e && e.message });
    return { ok: false };
  }
}

/* ══════════════════════ release log (admin) ═════════════════════════════ */

/* Mirrors sokoni-admin-updates.js: "live" ONLY when the entry records a deployment
   of the exact commit hosting's /version.json reports (passed in as liveCommit). */
function statusOf(e, liveCommit) {
  if (liveCommit && e.claim === 'deployed' && Array.isArray(e.commits) && e.commits.some((c) => {
    c = String(c).toLowerCase();
    return c.length >= 7 && (liveCommit.indexOf(c) === 0 || c.indexOf(liveCommit) === 0);
  })) return 'live';
  if (e.claim === 'deployed') return 'deployed';
  if (e.claim === 'not-deployed') return 'not-deployed';
  return 'committed';
}

function validateLogQuery(d) {
  d = d && typeof d === 'object' ? d : {};
  let limit = d.limit == null ? LOG_LIMIT_DEFAULT : Number(d.limit);
  if (!Number.isInteger(limit) || limit < 1) throw new HttpsError('invalid-argument', 'limit must be a positive integer.');
  limit = Math.min(limit, LOG_LIMIT_MAX);
  let offset = 0;
  if (d.cursor != null && d.cursor !== '') {
    const m = /^o:(\d{1,6})$/.exec(String(d.cursor));
    if (!m) throw new HttpsError('invalid-argument', 'cursor is not valid.');
    offset = parseInt(m[1], 10);
  }
  const type = d.type == null ? 'all' : String(d.type);
  if (!LOG_TYPES.has(type)) throw new HttpsError('invalid-argument', 'type is not valid.');
  const status = d.status == null ? 'all' : String(d.status);
  if (!LOG_STATUSES.has(status)) throw new HttpsError('invalid-argument', 'status is not valid.');
  const q = d.q == null ? '' : String(d.q).trim().toLowerCase().slice(0, LOG_QUERY_MAX);
  let liveCommit = null;
  if (d.liveCommit != null && d.liveCommit !== '') {
    liveCommit = String(d.liveCommit).toLowerCase();
    if (!/^[0-9a-f]{7,40}$/.test(liveCommit)) throw new HttpsError('invalid-argument', 'liveCommit is not a commit id.');
  }
  return { limit, offset, type, status, q, liveCommit };
}

function pageReleaseLog(log, query) {
  if (!log || !Array.isArray(log.entries)) throw new HttpsError('unavailable', 'The release log is not bundled with this deployment.');
  const hits = log.entries.filter((e) => {
    if (query.type !== 'all' && e.type !== query.type) return false;
    if (query.status !== 'all' && statusOf(e, query.liveCommit) !== query.status) return false;
    if (query.q) {
      const hay = (e.title + ' ' + (e.summary || '') + ' ' + (e.files || []).join(' ') + ' '
        + (e.commits || []).join(' ') + ' ' + (e.date || '')).toLowerCase();
      if (hay.indexOf(query.q) < 0) return false;
    }
    return true;
  });
  const page = hits.slice(query.offset, query.offset + query.limit);
  const next = query.offset + page.length;
  return {
    schema: log.schema,
    source: log.source || 'CHANGELOG.md',
    sourceSha256: log.sourceSha256 || null,
    entryCount: log.entries.length,
    total: hits.length,
    entries: page,
    nextCursor: next < hits.length ? 'o:' + next : null,
  };
}

async function handleAdminReleaseLog(req) {
  assertAdmin(req);
  const query = validateLogQuery(req.data);
  return pageReleaseLog(_deps.releaseLog(), query);
}

/* ══════════════════════ aggregate (scheduled) ═══════════════════════════ */

async function _count(q) {
  const snap = await q.count().get();
  return snap.data().count;
}

/** The live build, read over HTTPS from hosting's own /version.json. null + reason when unreadable. */
async function readLiveCacheVersion() {
  const ctl = typeof AbortController === 'function' ? new AbortController() : null;
  const t = ctl ? setTimeout(() => ctl.abort(), LIVE_FETCH_TIMEOUT_MS) : null;
  try {
    const r = await _deps.fetch(LIVE_VERSION_URL + '?cb=' + _deps.now(), {
      signal: ctl ? ctl.signal : undefined, headers: { 'cache-control': 'no-cache' },
    });
    if (!r || !r.ok) return { liveCacheVersion: null, liveError: 'version.json HTTP ' + (r && r.status) };
    const v = await r.json();
    const cv = v && typeof v.cacheVersion === 'string' ? v.cacheVersion : '';
    if (!CACHE_VERSION.test(cv)) return { liveCacheVersion: null, liveError: 'version.json carries no valid cacheVersion' };
    return { liveCacheVersion: cv, liveError: null };
  } catch (e) {
    return { liveCacheVersion: null, liveError: 'version.json unreadable (' + ((e && e.name) || 'error') + ')' };
  } finally { if (t) clearTimeout(t); }
}

/**
 * Compute the aggregate. Every figure is a Firestore count() over appInstalls with a
 * single-field filter — no composite index, one billed read per 1,000 index entries.
 *   devices    every device that has ever reported
 *   total      devices that reported the browser's appinstalled event (installed == true)
 *   standalone devices whose LAST report came from the installed app (covers iOS, which
 *              fires no appinstalled event)
 *   active7 / active30  devices with lastSeenAt in the last 7 / 30 days
 *   onLive     devices whose last report was the live cacheVersion
 *   behind     devices whose last report was any OTHER build = devices − onLive. Exact by
 *              definition; it includes devices not seen recently (a device that stopped
 *              reporting stays on the build it last reported).
 * onLive and behind are null (unknown) when the live build could not be read — never 0.
 */
async function computeStats(db, live, nowMs) {
  const coll = db.collection(INSTALLS);
  const ts = _deps.timestampFromMillis;
  const [devices, total, standalone, active7, active30] = await Promise.all([
    _count(coll),
    _count(coll.where('installed', '==', true)),
    _count(coll.where('standalone', '==', true)),
    _count(coll.where('lastSeenAt', '>=', ts(nowMs - 7 * DAY_MS))),
    _count(coll.where('lastSeenAt', '>=', ts(nowMs - 30 * DAY_MS))),
  ]);
  let onLive = null;
  let behind = null;
  if (live.liveCacheVersion) {
    onLive = await _count(coll.where('cacheVersion', '==', live.liveCacheVersion));
    behind = Math.max(0, devices - onLive);
  }
  /* "since": the first report ever received — when measurement actually began.
     Nothing before it is counted, and nothing before it is estimated. */
  let since = null;
  if (devices > 0) {
    const first = await coll.orderBy('firstSeenAt', 'asc').limit(1).get();
    const f = first.docs[0] && first.docs[0].get('firstSeenAt');
    since = f || null;
  }
  return {
    schema: 1,
    computedAt: _deps.serverTimestamp(),
    devices, total, standalone, active7, active30, onLive, behind,
    liveCacheVersion: live.liveCacheVersion,
    liveError: live.liveError,
    since,
  };
}

async function runScheduledStats() {
  const db = _deps.db();
  const live = await readLiveCacheVersion();
  const stats = await computeStats(db, live, _deps.now());
  /* set() without merge: the aggregate is replaced whole, so no stale field survives. */
  await db.collection(METRICS_COLL).doc(METRICS_DOC).set(stats);
  logger.info('[appInstallStats] computed', {
    devices: stats.devices, total: stats.total, active30: stats.active30,
    onLive: stats.onLive, liveCacheVersion: stats.liveCacheVersion, liveError: stats.liveError,
  });
  return stats;
}

function _iso(v) {
  if (!v) return null;
  if (typeof v.toDate === 'function') return v.toDate().toISOString();
  if (v instanceof Date) return v.toISOString();
  return null;
}

async function handleAdminGetAppInstallStats(req) {
  assertAdmin(req);
  const snap = await _deps.db().collection(METRICS_COLL).doc(METRICS_DOC).get();
  if (!snap.exists) return { state: 'not-computed-yet' };
  const d = snap.data() || {};
  /* A missing or malformed figure is returned as null (unknown), never coerced to 0. */
  const num = (x) => (typeof x === 'number' && Number.isFinite(x) ? x : null);
  return {
    state: 'computed',
    computedAt: _iso(d.computedAt),
    since: _iso(d.since),
    devices: num(d.devices),
    total: num(d.total),
    standalone: num(d.standalone),
    active7: num(d.active7),
    active30: num(d.active30),
    onLive: num(d.onLive),
    behind: num(d.behind),
    liveCacheVersion: typeof d.liveCacheVersion === 'string' ? d.liveCacheVersion : null,
    liveError: typeof d.liveError === 'string' ? d.liveError : null,
  };
}

