/* ══════════════════════════════════════════════════════════════════════════════
   SOKONI SHOP HOURS — the ONE shop availability evaluator  (2026-09-29)
   ══════════════════════════════════════════════════════════════════════════════
   One answer to "is this shop open right now — and when does that change?", used by:
     · the server (functions/kasshop.js effectiveForShop / publicShopState / getShopAvailability,
       and createCheckoutSession through availability-enforce),
     · the public storefront (sokoni-minishop.js) and the merchant-v2 Availability preview.
   The browser loads a BYTE-IDENTICAL copy, /sokoni-shop-hours.js, generated by
   scripts/build-shop-hours.js; scripts/test-shop-hours.js fails if the two differ. There is no
   second implementation to drift.

   INPUT (evaluate)
     live       { acceptingOrders, online, delivery, pickup }   shops/{id} — ABSENT = true
     hours      { sun..sat: { closed, periods:[{open:'HH:MM', close:'HH:MM'}] } }
                several periods = breaks between them; close <= open = runs past midnight;
                close '24:00' = until midnight
     overrides  { 'YYYY-MM-DD': { closed:true } | { closed:false } (open all day)
                                 | { periods:[…] } (special hours) , label? }
     temporaryClosure  { active:true, until: ms|null, note? }   — reopens by itself at `until`
     mode       'hours' (default) | 'appointment'
     timezone   IANA name (default Africa/Nairobi)
   OUTPUT
     { open, status, reason, source, state, date, timezone, today:[periods], closesAt, opensAt,
       special, temporaryClosure, appointment }
     status: open | closing_soon | break | closed | temporarily_closed | offline | appointment
     reason (compatible with the pre-2026-09-29 codes): within_hours | special_hours | no_schedule |
       outside_hours (also during a break) | closed_today | offline | temporarily_closed | appointment_only
   ══════════════════════════════════════════════════════════════════════════════ */
(function (root, factory) {
  var api = factory();
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.SokoniShopHours = api;
}(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';

  var DAYS = ['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat'];
  var LABEL = { sun: 'Sunday', mon: 'Monday', tue: 'Tuesday', wed: 'Wednesday', thu: 'Thursday', fri: 'Friday', sat: 'Saturday' };
  var DEFAULT_TZ = 'Africa/Nairobi';
  var CLOSING_SOON_MIN = 30;
  var HORIZON_DAYS = 14;

  function toMin(hhmm) {
    var m = /^(\d{1,2}):(\d{2})$/.exec(String(hhmm == null ? '' : hhmm).trim());
    if (!m) return null;
    var h = +m[1], mi = +m[2];
    if (mi > 59 || h > 24 || (h === 24 && mi !== 0)) return null;
    return h * 60 + mi;
  }
  function fromMin(m) {
    var v = ((m % 1440) + 1440) % 1440;
    var h = Math.floor(v / 60), mi = v % 60;
    return (h < 10 ? '0' : '') + h + ':' + (mi < 10 ? '0' : '') + mi;
  }
  /** '13:05' → '1:05 PM' ('00:00'/'24:00' → '12:00 AM') */
  function fmt12(hhmm) {
    var m = toMin(hhmm); if (m === null) return String(hhmm || '');
    m = m % 1440;
    var h = Math.floor(m / 60), mi = m % 60, ap = h < 12 ? 'AM' : 'PM', hh = h % 12 || 12;
    return hh + ':' + (mi < 10 ? '0' : '') + mi + ' ' + ap;
  }

  /* ── timezone ── offset (minutes east of UTC) of an IANA zone at an instant */
  var _dtf = {};
  function validTimezone(tz) {
    if (typeof tz !== 'string' || !tz || tz.length > 64) return false;
    try { new Intl.DateTimeFormat('en-US', { timeZone: tz }); return true; } catch (_) { return false; }
  }
  function tzOffsetMin(tz, atMs) {
    var zone = validTimezone(tz) ? tz : DEFAULT_TZ;
    try {
      var f = _dtf[zone] || (_dtf[zone] = new Intl.DateTimeFormat('en-US', { timeZone: zone, hourCycle: 'h23',
        year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', second: '2-digit' }));
      var p = {}; f.formatToParts(new Date(atMs)).forEach(function (x) { p[x.type] = x.value; });
      var asUtc = Date.UTC(+p.year, +p.month - 1, +p.day, +p.hour % 24, +p.minute, +p.second);
      return Math.round((asUtc - Math.floor(atMs / 1000) * 1000) / 60000);
    } catch (_) { return 180; }   /* an engine without Intl zones: East Africa Time */
  }
  function ymdOf(localMs) { return new Date(localMs).toISOString().slice(0, 10); }

  /* The periods a given local day actually has: its override if one exists, else the weekly day. */
  function periodsForDay(hours, overrides, ymd, dow) {
    var ov = overrides && overrides[ymd];
    if (ov && typeof ov === 'object') {
      if (ov.closed === true) return { periods: [], override: ov };
      if (Array.isArray(ov.periods) && ov.periods.length) return { periods: ov.periods, override: ov };
      if (ov.closed === false) return { periods: [{ open: '00:00', close: '24:00' }], override: ov };
    }
    var cfg = hours && hours[DAYS[dow]];
    if (!cfg || cfg.closed || !Array.isArray(cfg.periods)) return { periods: [], override: null };
    return { periods: cfg.periods, override: null };
  }

  function _state(live) {
    var l = live || {};
    return {
      acceptingOrders: l.acceptingOrders !== undefined ? !!l.acceptingOrders : true,
      online: l.online !== undefined ? !!l.online : true,
      delivery: l.delivery !== undefined ? !!l.delivery : true,
      pickup: l.pickup !== undefined ? !!l.pickup : true,
    };
  }
  function _hasSchedule(hours) {
    if (!hours || typeof hours !== 'object') return false;
    for (var i = 0; i < DAYS.length; i++) if (hours[DAYS[i]] && typeof hours[DAYS[i]] === 'object') return true;
    return false;
  }

  /**
   * THE evaluator. Pure: same input + same instant → same verdict, on the server and in the browser.
   */
  function evaluate(input, atMs) {
    var inp = input || {};
    var at = typeof atMs === 'number' ? atMs : Date.now();
    var tz = validTimezone(inp.timezone) ? inp.timezone : DEFAULT_TZ;
    var off = tzOffsetMin(tz, at);
    var local = at + off * 60000;
    var today = ymdOf(local);
    var nowMin = new Date(local).getUTCHours() * 60 + new Date(local).getUTCMinutes();
    var dow0 = new Date(local).getUTCDay();
    var state = _state(inp.live);
    var hours = inp.hours && typeof inp.hours === 'object' ? inp.hours : null;
    var overrides = inp.overrides && typeof inp.overrides === 'object' ? inp.overrides : {};
    var soon = typeof inp.closingSoonMin === 'number' ? inp.closingSoonMin : CLOSING_SOON_MIN;

    /* Intervals in minutes relative to TODAY's local midnight, from yesterday (its overnight tail) to the horizon. */
    var iv = [];
    var dayInfo = {};
    for (var d = -1; d <= HORIZON_DAYS; d++) {
      var ymd = ymdOf(local + d * 86400000);
      var dow = (dow0 + d + 7 * 3) % 7;
      var pf = periodsForDay(hours, overrides, ymd, dow);
      dayInfo[d] = { ymd: ymd, dow: dow, periods: pf.periods, override: pf.override };
      for (var i = 0; i < pf.periods.length; i++) {
        var a = toMin(pf.periods[i] && pf.periods[i].open), b = toMin(pf.periods[i] && pf.periods[i].close);
        if (a === null || b === null || a === b) continue;
        if (b <= a) b += 1440;                       /* runs past midnight into the next day */
        iv.push([a + d * 1440, b + d * 1440]);
      }
    }
    iv.sort(function (x, y) { return x[0] - y[0]; });
    var merged = [];                                  /* 08-13 + 13-18 is one open stretch, not a "closing soon" at 12:30 */
    iv.forEach(function (x) {
      var last = merged[merged.length - 1];
      if (last && x[0] <= last[1]) last[1] = Math.max(last[1], x[1]); else merged.push([x[0], x[1]]);
    });

    function point(m) {
      var dd = Math.floor(m / 1440);
      var info = dayInfo[dd] || { ymd: ymdOf(local + dd * 86400000), dow: (dow0 + dd + 21) % 7 };
      return { time: fromMin(m), ymd: info.ymd, dayLabel: LABEL[DAYS[info.dow]], inDays: dd, minutesAway: m - nowMin };
    }
    var todayOv = dayInfo[0].override;
    var special = todayOv ? { closed: todayOv.closed === true, periods: Array.isArray(todayOv.periods) ? todayOv.periods : [],
      label: typeof todayOv.label === 'string' ? todayOv.label.slice(0, 60) : null } : null;
    var base = { state: state, date: today, timezone: tz, today: dayInfo[0].periods, special: special,
      temporaryClosure: null, appointment: inp.mode === 'appointment', closesAt: null, opensAt: null,
      /* closed (any reason) → no orders and no channels; the open branches below say otherwise */
      ordersOpen: false, ordersCloseAt: null,
      fulfilment: { delivery: { available: false, until: null }, pickup: { available: false, until: null } } };
    function out(o) { var r = {}; var k; for (k in base) r[k] = base[k]; for (k in o) r[k] = o[k]; return r; }

    var cur = null, next = null;
    for (var j = 0; j < merged.length; j++) {
      if (merged[j][0] <= nowMin && nowMin < merged[j][1]) { cur = merged[j]; }
      else if (merged[j][0] > nowMin && !next) { next = merged[j]; }
      if (cur && next) break;
    }
    if (cur) { for (var q = 0; q < merged.length; q++) if (merged[q][0] >= cur[1]) { next = merged[q]; break; } }
    var opensAtPt = next ? point(next[0]) : null;

    /* 1. an explicit temporary closure (the owner said "we're closed until …") */
    var tc = inp.temporaryClosure;
    if (tc && tc.active === true && (tc.until == null || (typeof tc.until === 'number' && tc.until > at))) {
      var until = typeof tc.until === 'number' ? tc.until : null;
      var reopen = null;
      if (until) {
        var um = Math.round((until + off * 60000 - (local - nowMin * 60000)) / 60000);
        reopen = point(um);
        /* reopening lands on the timetable: if the shop would be closed at `until`, the next period start */
        var within = merged.some(function (x) { return x[0] <= um && um < x[1]; });
        if (!within && _hasSchedule(hours)) { var nx = null; for (var z = 0; z < merged.length; z++) if (merged[z][0] >= um) { nx = merged[z]; break; } reopen = nx ? point(nx[0]) : reopen; }
      }
      base.temporaryClosure = { until: until, note: typeof tc.note === 'string' ? tc.note.slice(0, 120) : null };
      return out({ open: false, status: 'temporarily_closed', reason: 'temporarily_closed', source: 'temporary', opensAt: reopen });
    }
    /* 2. the live switch (not taking orders / offline) */
    if (!state.online || !state.acceptingOrders) {
      return out({ open: false, status: 'offline', reason: 'offline', source: 'live', opensAt: null });
    }
    /* 3. appointment-only businesses have no walk-in hours — the booking engine decides slots */
    if (inp.mode === 'appointment') {
      return out({ open: false, status: 'appointment', reason: 'appointment_only', source: 'mode', opensAt: null });
    }
    /* 4. no timetable at all and no override today → open whenever online (unchanged behaviour) */
    if (!_hasSchedule(hours) && !todayOv) {
      return out({ open: true, status: 'open', reason: 'no_schedule', source: 'live', ordersOpen: true,
        fulfilment: { delivery: { available: state.delivery, until: null }, pickup: { available: state.pickup, until: null } } });
    }
    var src = todayOv ? 'override' : 'schedule';
    if (cur) {
      var left = cur[1] - nowMin;
      var cp = point(cur[1]);
      /* ORDER CUTOFF (owner-set, minutes before closing): the shop stays open, orders stop earlier. Never invented —
         absent a cutoff, orders run until closing. */
      var cut = typeof inp.orderCutoffMin === 'number' && inp.orderCutoffMin > 0 ? inp.orderCutoffMin : 0;
      var ordersCloseAt = cut && cur[1] - nowMin <= HORIZON_DAYS * 1440 ? point(cur[1] - cut) : null;
      /* DELIVERY / PICKUP "until" (owner-set daily end time, HH:MM): a channel ends earlier than the shop. */
      var chan = function (key, untilHHMM) {
        var on = state[key];
        var u = toMin(untilHHMM);
        if (!on) return { available: false, until: null };
        var end = cur[1];
        if (u !== null && u > 0) { var capAt = u; if (capAt < end) end = capAt; }
        return { available: nowMin < end, until: end >= cur[1] ? (cp ? cp.time : null) : fromMin(end) };
      };
      return out({ open: true, status: left <= soon ? 'closing_soon' : 'open', reason: todayOv ? 'special_hours' : 'within_hours',
        source: src, closesAt: cur[1] - nowMin > HORIZON_DAYS * 1440 ? null : cp, minutesToClose: left, opensAt: null,
        ordersOpen: !cut || left > cut, ordersCloseAt: ordersCloseAt,
        fulfilment: { delivery: chan('delivery', inp.deliveryUntil), pickup: chan('pickup', inp.pickupUntil) } });
    }
    /* closed now: a break if the shop already opened today and opens again later today */
    var openedToday = merged.some(function (x) { return x[0] >= 0 && x[1] <= nowMin; });
    if (openedToday && next && next[0] < 1440) {
      /* reason stays outside_hours (the pre-existing code consumers know); the STATUS says it is a break */
      return out({ open: false, status: 'break', reason: 'outside_hours', source: src, opensAt: opensAtPt });
    }
    return out({ open: false, status: 'closed', reason: todayOv && todayOv.closed === true ? 'closed_today' : 'outside_hours', source: src, opensAt: opensAtPt });
  }

  /* ── words: ONE phrasing for the storefront and the owner preview ── */
  function when(pt) {
    if (!pt) return '';
    var t = fmt12(pt.time);
    if (pt.inDays <= 0) return 'today at ' + t;
    if (pt.inDays === 1) return 'tomorrow at ' + t;
    if (pt.inDays < 7) return pt.dayLabel + ' at ' + t;
    return pt.ymd + ' at ' + t;
  }
  /** { tone: open|soon|break|closed|info, title, detail } */
  function headline(v) {
    if (!v) return { tone: 'info', title: 'Hours not available', detail: '' };
    switch (v.status) {
      case 'open':
        if (v.ordersOpen === false && v.ordersCloseAt) return { tone: 'soon', title: 'Open · orders closed for today', detail: 'Orders stopped at ' + fmt12(v.ordersCloseAt.time) + (v.closesAt ? ' · closes at ' + fmt12(v.closesAt.time) : '') };
        return { tone: 'open', title: v.reason === 'special_hours' ? 'Open · special hours' : 'Open now',
        detail: (v.closesAt ? 'Closes ' + (v.closesAt.inDays === 0 ? 'at ' + fmt12(v.closesAt.time) : when(v.closesAt)) : (v.reason === 'no_schedule' ? '' : 'Open all day'))
          + (v.ordersCloseAt ? ' · orders until ' + fmt12(v.ordersCloseAt.time) : '') };
      case 'closing_soon': return { tone: 'soon', title: 'Closing soon', detail: 'Closes in ' + v.minutesToClose + ' min · ' + fmt12(v.closesAt ? v.closesAt.time : '')
        + (v.ordersOpen === false ? ' · orders closed' : '') };
      case 'break': return { tone: 'break', title: 'On a break', detail: v.opensAt ? 'Reopens at ' + fmt12(v.opensAt.time) : '' };
      case 'temporarily_closed': return { tone: 'closed', title: 'Temporarily closed', detail: v.opensAt ? 'Reopens ' + when(v.opensAt) : 'Please check back soon' };
      case 'offline': return { tone: 'closed', title: 'Not taking orders right now', detail: '' };
      case 'appointment': return { tone: 'info', title: 'By appointment', detail: 'Book a time that suits you' };
      default:
        if (v.special && !v.special.closed && v.opensAt && v.opensAt.inDays === 0) {
          return { tone: 'closed', title: 'Special hours today' + (v.special.label ? ' — ' + v.special.label : ''), detail: 'Opens at ' + fmt12(v.opensAt.time) };
        }
        return { tone: 'closed', title: v.reason === 'closed_today' ? (v.special && v.special.label ? 'Closed today — ' + v.special.label : 'Closed today') : 'Closed',
        detail: v.opensAt ? 'Opens ' + when(v.opensAt) : '' };
    }
  }
  /** '🛵 Delivery until 7:00 PM' / '🛵 No delivery right now' — one phrasing for every surface. */
  function channelText(v, key) {
    var c = v && v.fulfilment && v.fulfilment[key];
    var label = key === 'delivery' ? '🛵 Delivery' : '🏬 Pickup';
    if (!c || !c.available) return label + (v && v.state && v.state[key] === false ? ' off' : ' closed now');
    return label + (c.until ? ' until ' + fmt12(c.until) : '');
  }
  function periodsText(periods) {
    if (!Array.isArray(periods) || !periods.length) return 'Closed';
    return periods.map(function (p) {
      return p.open === '00:00' && p.close === '24:00' ? 'Open all day' : fmt12(p.open) + ' – ' + fmt12(p.close);
    }).join(', ');
  }

  return { DAYS: DAYS, LABEL: LABEL, DEFAULT_TZ: DEFAULT_TZ, CLOSING_SOON_MIN: CLOSING_SOON_MIN,
    evaluate: evaluate, headline: headline, periodsText: periodsText, channelText: channelText, periodsForDay: periodsForDay,
    toMin: toMin, fromMin: fromMin, fmt12: fmt12, tzOffsetMin: tzOffsetMin, validTimezone: validTimezone };
}));
